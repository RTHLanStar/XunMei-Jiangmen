/* Local-only FAQ regression: run verify-faq.py first to generate the fixture. */
const fs = require('fs'), path = require('path'), http = require('http'), assert = require('assert');
const root = path.resolve(__dirname, '..'), dist = path.join(root, 'site/dist'), out = path.join(root, '材料/站内问答验证');
const runtime = require('./browser-runtime.cjs');
const report = {engine: 'Chromium; mobile emulation, not WeChat hardware', checks: []};
const server = http.createServer((req, res) => {
  const pathname = new URL(req.url, 'http://local').pathname;
  const file = pathname.endsWith('.css') ? path.join(dist, 'faq.css') : pathname.endsWith('.js') ? path.join(dist, 'faq.js') : path.join(out, 'faq-fixture.html');
  res.setHeader('Content-Type', pathname.endsWith('.css') ? 'text/css' : pathname.endsWith('.js') ? 'text/javascript' : 'text/html; charset=utf-8');
  fs.createReadStream(file).pipe(res);
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/v2.2/faq.html`;
  const browser = await runtime.chromium.launch({executablePath: runtime.executablePath});
  try {
    for (const width of [320, 390, 1440]) {
      const context = await browser.newContext({viewport: {width, height: 900}, hasTouch: width < 650, isMobile: width < 650});
      const page = await context.newPage(), errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(base);
      const count = await page.locator('.faq-item').count();
      assert.equal(count, 87);
      assert(await page.locator('.faq-controls').isVisible());
      assert((await page.locator('#faq-query').boundingBox()).height >= 44);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.locator('#faq-query').fill('陈皮');
      assert(await page.locator('#q-10').isVisible());
      assert(await page.locator('#q-18').isVisible());
      assert(await page.locator('#q-10 summary').textContent());
      assert.equal(await page.locator('#q-20').isVisible(), false);
      await page.locator('#faq-category').selectOption('food');
      assert(await page.locator('#q-18').isVisible());
      assert.equal(await page.locator('#q-10').isVisible(), false);
      await page.locator('#faq-query').fill('不存在的火星博物馆xyz');
      assert(await page.locator('#faq-empty').isVisible());
      assert.equal(await page.locator('.faq-item:visible').count(), 0);
      await page.locator('#faq-clear').click();
      assert.equal(await page.locator('.faq-item:visible').count(), count);
      assert.equal(await page.locator('#faq-category').inputValue(), 'all');
      await page.locator('#faq-query').fill('陈皮村 门票');
      assert(await page.locator('#q-10').isVisible());
      await page.locator('#faq-query').fill('我想去陈皮村');
      assert(await page.locator('#q-10').isVisible());
      await page.locator('#faq-category').selectOption('food');
      await page.locator('a[href="#q-16"]').first().click();
      await page.waitForFunction(() => document.getElementById('q-16').open);
      assert.equal(await page.locator('#faq-query').inputValue(), '');
      assert.equal(await page.locator('#faq-category').inputValue(), 'all');
      assert(await page.locator('#q-16').isVisible());
      await page.locator('#faq-clear').click();
      await page.locator('#q-61 summary').click();
      assert.equal(await page.locator('#q-61 li').count(), 7);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      if (width === 390) await page.locator('#q-61').screenshot({path: path.join(out, 'faq-390-expanded.png')});
      await page.locator('#faq-query').fill('<img src=x onerror=alert(1)>');
      assert.equal(await page.locator('.faq-panel img, .faq-panel script').count(), 0);
      await page.goto(base + '?q=' + encodeURIComponent('碉楼') + '#q-10');
      assert(await page.locator('#q-10').evaluate(el => el.open && !el.hidden));
      assert.equal(await page.locator('#faq-query').inputValue(), '');
      await page.goto(base + '?q=' + encodeURIComponent('外海面'));
      assert(await page.locator('#q-17').isVisible());
      assert.equal(await page.locator('#q-16').isVisible(), false);
      await page.locator('#faq-clear').click();
      await page.locator('#q-1 summary').focus();
      await page.keyboard.press('Enter');
      assert(await page.locator('#q-1').evaluate(el => el.open));
      await page.addStyleTag({content: '.faq-panel{font-size:200%}.faq-question{font-size:36px}.faq-answer{font-size:32px}'});
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      assert.deepEqual(errors, []);
      report.checks.push({width, count, search: true, category: true, empty: true, clear: true, commonQuestion: true, deepLink: true, keywordUrl: true, keyboard: true, largeText: true});
      await context.close();
    }
    const nojs = await browser.newContext({viewport: {width: 320, height: 900}, javaScriptEnabled: false});
    const page = await nojs.newPage();
    await page.goto(base);
    assert.equal(await page.locator('.faq-controls').isVisible(), false);
    assert.equal(await page.locator('.faq-item').count(), 87);
    await page.locator('#q-10 summary').click();
    assert(await page.locator('#q-10 .faq-answer').isVisible());
    report.checks.push({noJavaScript: true, fullStaticAnswers: true});
    await nojs.close();
    const fallback = await browser.newContext({viewport: {width: 320, height: 900}});
    await fallback.route('**/*.css', route => route.abort());
    const fallbackPage = await fallback.newPage();
    await fallbackPage.goto(base + '?q=' + encodeURIComponent('\"><img src=x onerror=alert(1)>'));
    assert.equal(await fallbackPage.locator('.faq-panel img, .faq-panel script').count(), 0);
    assert(await fallbackPage.locator('#faq-empty').isVisible());
    await fallbackPage.locator('#faq-clear').click();
    await fallbackPage.locator('#q-10 summary').click();
    assert(await fallbackPage.locator('#q-10 .faq-answer').isVisible());
    assert(await fallbackPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    report.checks.push({noExternalCSS: true, maliciousQuerySafe: true});
    await fallback.close();
    const fixture = fs.readFileSync(path.join(out, 'faq-fixture.html'), 'utf8')
      .replace('<link rel="stylesheet" href="/faq.css">', '<style>' + fs.readFileSync(path.join(dist, 'faq.css'), 'utf8') + '</style>')
      .replace('<script src="/faq.js" defer></script>', '<script>' + fs.readFileSync(path.join(dist, 'faq.js'), 'utf8') + '</script>');
    const localPath = path.join(out, 'faq-file.html');
    fs.writeFileSync(localPath, fixture);
    const offline = await browser.newContext({viewport: {width: 390, height: 844}});
    const offlinePage = await offline.newPage(), network = [], offlineErrors = [];
    offlinePage.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
    offlinePage.on('pageerror', error => offlineErrors.push(error.message));
    await offlinePage.goto(require('url').pathToFileURL(localPath).href + '?q=' + encodeURIComponent('陈皮'));
    assert(await offlinePage.locator('#q-10').isVisible());
    assert.equal(await offlinePage.locator('#q-20').isVisible(), false);
    await offlinePage.locator('#faq-query').fill('外海面');
    assert(await offlinePage.locator('#q-17').isVisible());
    assert.deepEqual(network, []);
    assert.deepEqual(offlineErrors, []);
    report.checks.push({fileProtocol: true, noNetworkRequests: true});
    await offline.close();
    report.passed = true;
    fs.writeFileSync(path.join(out, '浏览器验证.json'), JSON.stringify(report, null, 2));
    console.log(`PASS: FAQ ${report.checks.length} scenarios; mobile layout, search/category, keyboard, deep links, safe query, no JavaScript.`);
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
